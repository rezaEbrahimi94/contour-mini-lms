// Generates the OpenAPI document and the browser client's types from the Zod
// contracts, or with --check fails when the committed files are stale.
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";
import { format } from "prettier";
import { z } from "zod";
import {
  bookingSchema,
  changeSchema,
  consultationSchema,
  consultationPageSchema,
} from "../features/consultations/contracts.ts";
import { problemSchema } from "../lib/http/problem.ts";
import { projectRoot } from "../tests/support/stack.ts";

const models = {
  Booking: bookingSchema,
  Change: changeSchema,
  Consultation: consultationSchema,
  Page: consultationPageSchema,
  Problem: problemSchema,
};
const schemas = Object.fromEntries(
  Object.entries(models).map(([key, schema]) => {
    const definition = z.toJSONSchema(schema, { io: "input" });
    // OpenAPI names the JSON Schema dialect once, for the whole document.
    delete definition.$schema;
    return [key, definition];
  }),
);
const json = (name: keyof typeof models) => ({
  "application/json": { schema: { $ref: "#/components/schemas/" + name } },
});
const requestBody = (name: keyof typeof models) => ({
  required: true,
  content: json(name),
});
const response = (description: string, name: keyof typeof models) => ({
  description,
  content: json(name),
});
const failure = response("Request declined or service unavailable", "Problem");
const etag = {
  ETag: {
    description: "Quoted current booking revision",
    schema: { type: "string" },
  },
};
const conditionalErrors = {
  400: failure,
  404: failure,
  412: response("Booking revision has changed", "Problem"),
  428: response("Booking revision required", "Problem"),
};
const spec = {
  openapi: "3.1.0",
  info: {
    title: "Contour consultations",
    version: "1.0.0",
    description:
      "Uses the signed-in student's Supabase session cookies. Send mutations from the configured application origin.",
  },
  components: { schemas },
  paths: {
    "/api/consultations": {
      get: {
        operationId: "listOwnConsultations",
        parameters: [
          {
            name: "page",
            in: "query",
            schema: { type: "integer", minimum: 1, default: 1 },
          },
        ],
        responses: {
          200: response("Student schedule", "Page"),
          default: failure,
        },
      },
      post: {
        operationId: "bookConsultation",
        requestBody: requestBody("Booking"),
        responses: {
          201: { ...response("Created", "Consultation"), headers: etag },
          200: {
            ...response("Idempotent replay", "Consultation"),
            headers: etag,
          },
          409: failure,
          429: response("Student booking limit reached", "Problem"),
          default: failure,
        },
      },
    },
    "/api/consultations/{id}": {
      parameters: [
        {
          name: "If-Match",
          in: "header",
          required: true,
          description:
            "One strong, quoted revision from the booking. Wildcards, lists and weak tags are rejected.",
          schema: { type: "string" },
        },
        {
          name: "id",
          in: "path",
          required: true,
          schema: { type: "string", format: "uuid" },
        },
      ],
      patch: {
        operationId: "changeOwnConsultation",
        requestBody: requestBody("Change"),
        responses: {
          204: { description: "Saved; empty response", headers: etag },
          ...conditionalErrors,
          default: failure,
        },
      },
      delete: {
        operationId: "cancelOwnConsultation",
        responses: {
          204: { description: "Cancelled; empty response" },
          ...conditionalErrors,
          default: failure,
        },
      },
    },
  },
};
// The generator receives the document as JSON text, exactly as any other
// consumer would, and validates it as OpenAPI before producing types.
const document = JSON.stringify(spec);
const types =
  "// Generated by npm run contracts. Edit the schemas or operations to change this file.\n" +
  astToString(await openapiTS(document));
const outputs = [
  {
    path: "docs/consultations.openapi.json",
    content: document,
    parser: "json",
  },
  {
    path: "features/consultations/api.d.ts",
    content: types,
    parser: "typescript",
  },
];
for (const { path, content, parser } of outputs) {
  const file = join(projectRoot, path);
  const formatted = await format(content, { parser });
  if (process.argv.includes("--check")) {
    if ((await readFile(file, "utf8")) !== formatted)
      throw new Error("Regenerate " + path + " with npm run contracts");
  } else await writeFile(file, formatted);
}
